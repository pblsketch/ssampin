/**
 * 클라우드 자료의 무결성이 깨졌을 때 **일부러 동기화를 중단시키는** 오류.
 *
 * ## 왜 보통 오류와 구분해야 하는가
 *
 * 동기화 중 나는 실패는 성격이 둘로 갈린다.
 *
 * - **일시적 실패** (네트워크 끊김, 한 파일 업로드 오류) — 그 항목만 건너뛰고 계속해야 한다.
 *   여기서 사이클 전체를 멈추면 사진 한 장 때문에 출결·기록까지 동기화가 안 된다.
 * - **무결성 위반** (장부와 실제 파일이 다름, 소유 기기를 확인할 수 없음) —
 *   **반드시 멈춰야 한다.** 그대로 진행하면 다른 기기의 자료를 덮어써 데이터가 사라질 수 있다.
 *
 * 항목별 예외 처리를 넣을 때 이 둘을 뭉뚱그리면 **안전장치가 조용히 무력화된다.**
 * (실제로 그렇게 만들었다가 기존 안전 테스트가 빨간불로 잡아 줬다.)
 * 그래서 무결성 위반만 이 타입으로 던지고, 항목별 catch 는 이 타입을 다시 던진다.
 */
export class SyncIntegrityError extends Error {
  constructor(message: string) {
    super(message);
    this.name = 'SyncIntegrityError';
  }
}
