/**
 * 옆핀의 지연 동작(180ms 펼침 / 400ms 접힘 / 10초 파기)을 맡는 포트.
 *
 * `setTimeout`을 코드 여기저기서 직접 부르지 않고 이 포트로 모은 이유:
 * 타이머가 흩어져 있으면 "분명 취소했는데 왜 닫히지" 같은 문제를 추적할 수 없고,
 * 무엇보다 실제 시간을 기다리지 않고는 테스트할 수 없다.
 *
 * 예약은 한 번에 하나만 살아 있다. 옆핀의 지연 동작은 서로 배타적이라
 * (펼치는 중에 접기를 예약할 일이 없다) 여러 개를 동시에 둘 이유가 없다.
 */
export interface SidePinScheduler {
  /** 현재 시각 (ms) */
  now(): number;
  /** 기존 예약을 취소하고 새로 예약한다 */
  schedule(dueAtMs: number, callback: () => void): void;
  /** 예약된 동작을 취소한다. 예약이 없으면 아무 일도 하지 않는다. */
  cancel(): void;
}
