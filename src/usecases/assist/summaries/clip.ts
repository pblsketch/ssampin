/**
 * 긴 자유 글을 서버 상한 안에 들어가게 자른다.
 *
 * ★이것은 **개인정보 축소가 아니라 전송 한계**다. 서버(`assistRequest.ts`)는 도구 결과
 * 하나당 4,000자를 넘으면 400 으로 거절하므로, 넘치면 선생님은 **이유를 알 수 없는 실패**만
 * 본다. 오너 결정 ①("메모 내용은 제한 없이 보낸다")은 *무엇을* 보낼지에 대한 결정이고,
 * 여기서 다루는 것은 *얼마나 담기는가* 라는 물리적 상한이다.
 *
 * 자른 사실은 호출자가 `truncated` 로 드러낸다 — 조용한 절단은 "다 보여줬다"로 읽힌다.
 */
export function clip(text: string, max: number): string {
  return text.length <= max ? text : `${text.slice(0, max)}…`;
}
