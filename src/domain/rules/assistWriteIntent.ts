/**
 * 쌤핀 AI — "이 질문이 무언가를 **바꾸려는** 말인가" (순수 함수)
 *
 * ★이것으로 도구를 고르지 않는다. 도구 선택은 모델이 한다(옵션 A). 이 판정은 딱 하나,
 * **2왕복째에 도구 목록을 실을지**를 정하는 데만 쓴다.
 *
 * 왜 필요했나 — 실측(2026-08-23, UltraQA)
 * 고치기·지우기는 모델이 "먼저 목록을 보고" 오기 때문에 2왕복째에도 도구가 있어야 한다
 * (없으면 지우자고 말할 방법이 없다). 그런데 도구를 실었더니 이 모델은 **문장 대신 늘
 * 도구를 한 번 더 부른다** — 조회 질문 5개를 재 보니 5/5 였다. 그러면 앱이 문장을 받으러
 * 한 번 더 물어야 해서 조회 한 번이 3요청이 되고, 하루 상한(40요청/설치) 안에서 물어볼
 * 수 있는 횟수가 20번에서 13번으로 준다. 계획서 §4 가 지키기로 한 값이 조용히 깨진다.
 *
 * ★틀려도 값이 싸다. 놓치면(쓰기 질문인데 못 알아보면) 조회로 답하고 선생님이 다시
 * 말하면 된다. 반대로 잘못 걸려도 왕복이 한 번 늘 뿐 저장되는 것은 없다 — 저장은
 * 언제나 [실행] 버튼이 한다. 그래서 **넓게 잡되 조회의 흔한 말은 넣지 않는다**
 * ("알려줘"·"보여줘"·"뭐 있어"는 여기 없다).
 */

/**
 * 어느 쪽으로도 안 읽히는 말 — 이것만 있으면 바꾸려는 뜻이다.
 * ("지워", "삭제", "취소", "바꿔"…)
 */
const ACTION =
  /지워|지우|삭제|없애|빼줘|빼주|취소|바꿔|바꾸|고쳐|고치|수정|변경|옮겨|만들어|만들자|넣어|넣자|붙여|생성|잡아줘|잡아주|완료해|완료했|체크해|끝냈|끝났|다 했/;

/**
 * ★한국어는 **어미가 뜻을 가른다.** 같은 말뿌리라도
 *   "등록해**줘**"·"적어**줘**" = 시키는 말 (쓰기)
 *   "등록해**둔**"·"적어**놨**" = 있는 것을 말하는 말 (조회)
 * 이라서, 말뿌리만 보면 "메모에 뭐라고 적어놨더라?"(조회)가 쓰기로 걸린다 —
 * 실제로 그렇게 걸렸다(UltraQA 2026-08-23). 그래서 이 뿌리들은 **시키는 어미가
 * 붙었을 때만** 인정한다.
 */
const ASK_TO_WRITE =
  /(적어|기록|등록|저장|남겨|남기|추가|써)\s*(해)?\s*(줘|주세요|주시|주라|자|둬)/;

export function mentionsWriteIntent(question: string): boolean {
  return ACTION.test(question) || ASK_TO_WRITE.test(question);
}
