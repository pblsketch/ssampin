/**
 * 쌤핀 AI — "바꾸려는 말인가" 판정 (UltraQA 2026-08-23)
 *
 * ★이 판정은 도구를 고르지 않는다. **2왕복째에 도구 목록을 실을지**만 정한다.
 * 그래서 틀려도 값이 싸다 — 놓치면 조회로 답하고 선생님이 다시 말하면 되고,
 * 잘못 걸려도 왕복이 한 번 늘 뿐 저장되는 것은 없다(저장은 [실행] 버튼이 한다).
 *
 * 다만 **조회의 흔한 말이 걸리면 안 된다.** 그러면 모든 질문이 3왕복이 되어 하루에
 * 물어볼 수 있는 횟수가 20번 → 13번으로 줄고, 이 판정을 만든 이유가 사라진다.
 */
import { describe, expect, it } from 'vitest';

import { mentionsWriteIntent } from '../assistWriteIntent';

describe('바꾸려는 말은 잡는다', () => {
  it.each([
    '장보기 할 일 지워줘',
    '할 일 목록에서 장보기 삭제해줘',
    '내일까지 결재 올리기 할 일로 넣어줘',
    '9월 3일에 학부모 상담 일정 추가해줘',
    '메모로 남겨줘 — 수행평가 일정 정리하기',
    '3학년 2반 내일 3교시 진도 2단원으로 적어줘',
    '즐겨찾기에 학교알리미 등록해줘',
    '장보기 마감 9월 1일로 바꿔줘',
    '할 일 제목 좀 고쳐줘',
    '장보기 다 했어 체크해줘',
    '학부모 총회 일정 취소해줘',
    '노트 페이지 이름 바꿔줘',
    '3학년 수학 노트책 만들어줘',
  ])('%s', (question) => {
    expect(mentionsWriteIntent(question)).toBe(true);
  });
});

describe('★학생 쓰기 3종(출결·관찰·채점)의 말 — 이게 비어 있어 실사용에서 안 됐다', () => {
  /**
   * 2026-08-25 실사용: "오늘 ○○○ 결석이야 결석 처리해줘" 가 조회로만 답했다.
   * set_attendance 는 이미 등록돼 있었다 — 다만 "결석"이 지름길에 걸려 카드가
   * 먼저 만들어지면 이 판정이 참이어야만 도구 목록이 실린다(wantsToolSelection).
   * 그래서 모델은 **그 도구를 본 적이 없다.** 쓰기를 열 때 이 문턱까지 같이
   * 열지 않으면 기능이 붙어 있어도 닿지 않는다.
   */
  it.each([
    '오늘 가가가 결석이야 결석 처리해줘',
    '12번 조퇴 처리해 주세요',
    '3번 지각으로 표시해줘',
    '오늘 우리 반 출결 입력해줘',
    '5번 출석 찍어줘',
    '7번 수업 태도 관찰 기록해줘',
    '주장의 명확성 잘함으로 채점해줘',
  ])('%s', (question) => {
    expect(mentionsWriteIntent(question)).toBe(true);
  });
});

describe('★조회의 흔한 말은 걸리지 않는다 — 걸리면 모든 질문이 3왕복이 된다', () => {
  it.each([
    '할 일 뭐 있어?',
    '이번 주 급식 뭐 나와?',
    '내일 시간표 알려줘',
    '메모에 뭐라고 적어놨더라?',
    '이번 주 일정 알려줘',
    '오늘 우리 반 출결 어때?',
    '이번 달 기록 몇 건이야',
    '담당 학급 목록 보여줘',
    '즐겨찾기에 등록해둔 사이트 알려줘',
    '2학기 지필 평균이랑 성취도 분포 알려줘',
    '지금 자리 배치에 빈자리 몇 개야?',
    '이번 주 어떻게 돌아가는지 한눈에 보여줘',
    '출결 어떻게 처리했어?',
    '입력해 놓은 거 보여줘',
    '지각 표시된 학생 몇 명이야?',
    '채점 결과 알려줘',
  ])('%s', (question) => {
    expect(mentionsWriteIntent(question)).toBe(false);
  });
});
